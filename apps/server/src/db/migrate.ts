export async function migrate(db: NodePgDatabase<Record<string, never>>): Promise<number> {
  await db.execute(sql`CREATE TABLE IF NOT EXISTS schema_migrations (version INT PRIMARY KEY, name TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())`);
  const applied = await db.execute<{ version: number }>(sql`SELECT version FROM schema_migrations ORDER BY version`);
  const appliedSet = new Set((applied.rows ?? []).map((r) => Number(r.version)));
  let n = 0;
  for (const m of MIGRATIONS) {
    if (appliedSet.has(m.version)) continue;
    for (const stmt of m.statements) {
      await db.execute(sql.raw(stmt));
    }
    await db.execute(sql`INSERT INTO schema_migrations (version, name) VALUES (${m.version}, ${m.name})`);
    n++;
  }
  return n;
}
